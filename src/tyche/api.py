"""tyche HTTP service layer — exposes cast() as REST (thin wrapper, SaaS skeleton).

It does three things only: validate the request -> cast() -> serialize. No business logic, no
state, no auth (auth / rate limiting / log redaction are left to the gateway at deploy time; see
docs §10 on PIPL).

Run:
    pip install -e ".[api]"
    uvicorn tyche.api:app --reload
Docs: /docs (Swagger) and /redoc
"""

from __future__ import annotations

from datetime import datetime
from typing import Literal, Optional

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from . import __version__
from .chart.config import ChartConfig
from .chart.luck import fleeting_year, fleeting_years, fleeting_months
from .chart.pillars import build_chart
from .reading import build_reading_prompt
from .report import cast

_DT_FORMATS = ("%Y-%m-%d %H:%M", "%Y-%m-%d %H:%M:%S")


def _parse_dt(s: str) -> datetime:
    try:
        return datetime.fromisoformat(s)
    except ValueError:
        pass
    for fmt in _DT_FORMATS:
        try:
            return datetime.strptime(s, fmt)
        except ValueError:
            continue
    raise HTTPException(
        status_code=422,
        detail=f"cannot parse datetime: {s!r} (use 'YYYY-MM-DD HH:MM' or ISO 8601)",
    )


class ChartRequest(BaseModel):
    datetime: str = Field(..., examples=["1990-06-15 14:30"], description="birth datetime (Gregorian)")
    gender: Literal["male", "female"] = "male"
    longitude: Optional[float] = Field(
        None, description="birth longitude, east positive; if given, apply true solar time, else use clock time"
    )
    reference_pillar: Literal["day", "year"] = Field(
        "day", description="太极点: day=子平 (day as the self) / year=禄命星命 (year as the root)"
    )
    school: Literal["ziping", "luming", "xingming"] = "ziping"
    pattern_school: Literal["ziping", "gufa_dangling"] = Field(
        "ziping", description="取格 school: ziping=子平真诠 / gufa_dangling=古法当令"
    )
    use_true_solar_time: bool = True

    def to_config(self) -> ChartConfig:
        return ChartConfig(
            reference_pillar=self.reference_pillar,
            school=self.school,
            gender=self.gender,
            longitude=self.longitude,
            use_true_solar_time=self.use_true_solar_time,
            pattern_school=self.pattern_school,
        )


class ReadingRequest(ChartRequest):
    question: str = Field("综合命理", description="the question / topic to read")


class FleetingRequest(ChartRequest):
    year: int = Field(..., examples=[2025], description="start Gregorian year")
    end_year: Optional[int] = Field(
        None, description="if given, return 流年 over the closed range [year, end_year]; otherwise just the single year"
    )
    with_months: bool = Field(
        False, description="for a single year, also include the 12 流月 (month 干支 + 太极点 十神); ignored for range queries"
    )


app = FastAPI(
    title="tyche",
    version=__version__,
    description="命理 charting engine — 子平/禄命 dual paradigm, configurable 太极点",
)


@app.get("/health")
def health() -> dict:
    return {"status": "ok", "version": __version__}


@app.post("/v1/chart")
def post_chart(req: ChartRequest) -> dict:
    """Deterministic charting + rule analysis; returns the full chart structure (ChartReport.to_dict)."""
    report = cast(_parse_dt(req.datetime), req.to_config())
    return report.to_dict()


@app.post("/v1/reading")
def post_reading(req: ReadingRequest) -> dict:
    """Chart structure + the reading prompt (system/user) for an LLM; the reading itself is generated by the caller."""
    report = cast(_parse_dt(req.datetime), req.to_config())
    return {
        "report": report.to_dict(),
        "prompt": build_reading_prompt(report, req.question),
    }


@app.post("/v1/fleeting")
def post_fleeting(req: FleetingRequest) -> dict:
    """流年: a year's 干支 + 十神 (reference follows the 太极点) + enclosing 大运/小运/旬空.

    With end_year, returns the per-year list (years); otherwise a single year (year).
    """
    chart = build_chart(_parse_dt(req.datetime), req.to_config())
    if req.end_year is not None:
        return {"years": fleeting_years(chart, req.year, req.end_year)}
    out = {"year": fleeting_year(chart, req.year)}
    if req.with_months:
        out["months"] = fleeting_months(chart, req.year)
    return out
